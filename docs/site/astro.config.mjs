// @ts-check
import { cpSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { defineConfig } from 'astro/config';
import starlight from '@astrojs/starlight';

const site = 'https://spock.cc';

// The repo's brand kit, served at /brand/ as-is: the icons, webmanifest and og-image
// link to it by that path. It isn't copied into this folder, so brand/ stays the only copy.
const brandDir = fileURLToPath(new URL('../../brand/', import.meta.url));

/** @returns {import('astro').AstroIntegration} */
function brandAssets() {
	return {
		name: 'spock-brand-assets',
		hooks: {
			// In dev, hand /brand/* to Vite's /@fs/ file server.
			'astro:server:setup': ({ server }) => {
				server.middlewares.use('/brand', (req, _res, next) => {
					req.url = `/@fs${brandDir}${req.url?.replace(/^\//, '')}`;
					next();
				});
			},
			'astro:build:done': ({ dir }) => {
				cpSync(brandDir, fileURLToPath(new URL('brand/', dir)), { recursive: true });
			},
		},
	};
}

// https://astro.build/config
export default defineConfig({
	site,
	server: { port: 4322 },
	// The pages live outside this folder, so their imports wouldn't find its node_modules.
	// Resolve the ones they use from here instead.
	vite: { resolve: { dedupe: ['@astrojs/starlight'] } },
	integrations: [
		brandAssets(),
		starlight({
			title: 'spock',
			logo: {
				light: '../../brand/logo/svg/spock-wordmark-blue.svg',
				dark: '../../brand/logo/svg/spock-wordmark-white.svg',
				alt: 'spock',
				replacesTitle: true,
			},
			favicon: '/brand/icons/favicon.svg',
			head: [
				{ tag: 'link', attrs: { rel: 'icon', href: '/brand/icons/favicon.ico', sizes: '48x48' } },
				{ tag: 'link', attrs: { rel: 'apple-touch-icon', href: '/brand/icons/apple-touch-icon.png' } },
				{ tag: 'link', attrs: { rel: 'manifest', href: '/brand/icons/site.webmanifest' } },
				{ tag: 'meta', attrs: { name: 'theme-color', content: '#3D5AFE' } },
				{ tag: 'meta', attrs: { property: 'og:image', content: `${site}/brand/social/og-image.png` } },
				{ tag: 'meta', attrs: { property: 'og:image:width', content: '1200' } },
				{ tag: 'meta', attrs: { property: 'og:image:height', content: '630' } },
			],
			customCss: ['./src/styles/brand.css'],
			social: [
				{ icon: 'github', label: 'GitHub', href: 'https://github.com/north-shore-software/spock' },
			],
			// Starlight only runs its Markdown plugins (asides, heading links) on src/content/docs
			// unless told otherwise, and the pages live one level up.
			markdown: { processedDirs: ['..'] },
			// Listed rather than autogenerated: autogenerate assumes the pages are in
			// src/content/docs. One group per package.
			sidebar: [
				{ label: 'Start here', items: ['getting-started'] },
				{
					label: '@spock/router',
					items: ['router', 'router/routes', 'router/data', 'router/pages', 'router/links', 'router/reference'],
				},
				{ label: '@spock/toolbar', items: ['toolbar', 'toolbar/apps', 'toolbar/devtools'] },
			],
		}),
	],
});
